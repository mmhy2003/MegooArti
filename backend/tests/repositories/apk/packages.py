def tar_of(files: dict[str, bytes], *, end: bool) -> bytes:
    """A tar, with its end or, as a signature and a control part have it, without."""
    buffer = io.BytesIO()
    for name, data in files.items():
        member = tarfile.TarInfo(name)
        member.size = len(data)
        buffer.write(member.tobuf(format=tarfile.USTAR_FORMAT))
        buffer.write(data + b"\0" * (-len(data) % 512))
    return buffer.getvalue() + (b"\0" * 1024 if end else b"")


def pkginfo(
    name: str = "megooarti-hello",
    version: str = "1.0-r0",
    arch: str = "noarch",
    description: str = "Says hello",
    extra: str = "",
) -> str:
    return (
        "# Generated by abuild 3.17.0-r0\n"
        f"pkgname = {name}\npkgver = {version}\npkgdesc = {description}\n"
        "url = https://example.com/megooarti-hello\nbuilddate = 1792051327\n"
        f"packager = Unknown\nsize = 48\narch = {arch}\norigin = {name}\n"
        f"license = MIT\n{extra}depend = busybox\n"
    )


def make_apk(
    info: str | None = None,
    *,
    signed: bool = True,
    data: bytes = b"the files of the package",
) -> bytes:
    """A package whose `.PKGINFO` is `info`, as abuild lays one out."""
    streams = []
    if signed:
        streams.append(tar_of({".SIGN.RSA.someone.rsa.pub": b"\x01" * 512}, end=False))
    streams.append(tar_of({".PKGINFO": (info or pkginfo()).encode()}, end=False))
    streams.append(tar_of({"usr/share/megooarti/file": data}, end=True))
    return b"".join(gzip.compress(stream, mtime=0) for stream in streams)


async def pieces(data: bytes, size: int = 300) -> AsyncIterator[bytes]:
    """Bytes as they arrive, a piece at a time."""
    for at in range(0, len(data), size):
        yield data[at : at + size]
